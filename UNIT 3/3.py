import math

a = 25
b = 4

print("Square root of", a, "=", math.sqrt(a))
print("Factorial of", b, "=", math.factorial(b))
print("Power of", a, "raised to", b, "=", math.pow(a, b))
print("Ceiling of 4.3 =", math.ceil(4.3))
print("Floor of 4.7 =", math.floor(4.7))
print("GCD of 12 and 18 =", math.gcd(12, 18))
print("Value of pi =", math.pi)
print("Sine of 30 degrees =", math.sin(math.radians(30)))
print("Logarithm of 10 =", math.log10(10))
print("Absolute value of -15 =", math.fabs(-15))