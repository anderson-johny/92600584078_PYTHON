print('=================DEMONSTRATING BREAK STATEMENT====================')
for i in range(1,11):
    if i==5:
        break
    else:
        print(i)
print('=================DEMONSTRATING CONTINUE STATEMENT====================')
for i in range(1,11):
    if i==5:
        continue
    else:
        print(i)
print('=================DEMONSTRATING Pass STATEMENT====================')
for i in range(1,10):
    if i==5:
        pass
    else:
        print(i)